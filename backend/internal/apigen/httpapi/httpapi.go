	fmt.Fprintf(b, "// Update handles PATCH /%s/{id}: apply the request body to an existing row.\n", plural)
	b.WriteString("// The path id is authoritative. The write goes through the syncer's Apply.\n")
	b.WriteString("func Update() http.HandlerFunc {\n")
	b.WriteString("\treturn func(w http.ResponseWriter, r *http.Request) {\n")
	gateBlock(b, gate)
	b.WriteString("\t\tid := r.PathValue(\"id\")\n")
	b.WriteString("\t\tif _, found, err := query.Get(r.Context(), db.GetDB(), resource, a.WorkspaceID, id); err != nil {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusInternalServerError, \"internal error\")\n")
