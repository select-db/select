// Package httpapi projects the apigen entity model into the generated REST route
// table under internal/api/gen. Mirroring the syncer's layout, each @app.api
// entity gets its own package folder: resource.go (the queryable field spec) and
// one file per endpoint (list.go, get.go, create.go, …), plus a routes.go, with
// a top-level routes.go aggregating them.
//
// Each endpoint file holds the FULL handler inlined — the gate check, the query
// runtime call, the syncer Apply, the status codes — not a delegation to a
// generic helper. This is code generation: the boilerplate is the point. A
// reader opens internal/api/gen/role/create.go and sees exactly what a role
// create does, top to bottom, without following an abstraction into the rest
// package. The rest package holds only primitives (response writers, the authz
// gate, body decode) the handlers call. Field specs come from the same IR that
// produces the OpenAPI filterable-fields table, so the API and its docs
// advertise and accept the same fields/operators.
package httpapi

import (
	"fmt"
	"go/format"
	"strings"

	"backend/internal/apigen/codegen"
	"backend/internal/apigen/schema"
	"backend/internal/apigen/syncer"
)

const genHeader = "// Code generated by apigen. DO NOT EDIT.\n\n"

// Import paths the generated handlers reference.
const (
	pkgDB    = "backend/db"
	pkgQuery = "backend/internal/api/query"
	pkgRest  = "backend/internal/api/rest"
	pkgAuthz = "backend/internal/authz"
	pkgTypes = "backend/internal/syncer/types"
	pkgCore  = `core "github.com/selectDb/dialect/core"`
)

// EmitRoutes renders the generated REST route table as a set of files rooted at
// internal/api/gen: one folder per @app.api entity plus the top-level routes.go.
func EmitRoutes(entities []schema.Entity) ([]codegen.GenFile, error) {
	var apis []schema.Entity
	for _, e := range entities {
		if len(e.API) > 0 {
			apis = append(apis, e)
		}
	}

	var files []codegen.GenFile
	for _, e := range apis {
		fs, err := emitEntity(e)
		if err != nil {
			return nil, err
		}
		files = append(files, fs...)
	}
	top, err := emitTopRoutes(apis)
	if err != nil {
		return nil, err
	}
	return append(files, top), nil
}

// emitEntity produces one entity's package folder: resource.go, a file per op,
// and routes.go. The folder/package is named for the table (as the syncer's is).
func emitEntity(e schema.Entity) ([]codegen.GenFile, error) {
	dir := e.Table + "/"
	var files []codegen.GenFile

	res, err := emitResource(e)
	if err != nil {
		return nil, err
	}
	files = append(files, codegen.GenFile{Name: dir + "resource.go", Content: res})

	for _, op := range e.API {
		f, err := emitOp(e, op)
		if err != nil {
			return nil, err
		}
		files = append(files, codegen.GenFile{Name: dir + op.Op + ".go", Content: f})
	}

	routes, err := emitEntityRoutes(e)
	if err != nil {
		return nil, err
	}
	return append(files, codegen.GenFile{Name: dir + "routes.go", Content: routes}), nil
}

// emitResource writes the table's shared data: the query.Resource the read
// handlers run over (the exposed fields and their operators, the default sort,
// the keyset primary key) and the naming constants the handlers reference. This
// is data, not logic — it is the one thing every op over the table shares, so it
// lives in one file rather than being copied into each handler.
func emitResource(e schema.Entity) (string, error) {
	pk, err := pkFieldName(e)
	if err != nil {
		return "", err
	}

	b := &strings.Builder{}
	b.WriteString(genHeader)
	fmt.Fprintf(b, "package %s\n\n", e.Table)
	b.WriteString("import \"backend/internal/api/query\"\n\n")

	fmt.Fprintf(b, "// resource is the queryable shape of the %s table: the fields the API\n", e.Table)
	b.WriteString("// exposes, the operators each accepts, the default sort, and the keyset\n")
	b.WriteString("// primary key. The list and get handlers run over it.\n")
	b.WriteString("var resource = query.Resource{\n")
	fmt.Fprintf(b, "\tTable: %q, PK: %q, DefaultSort: %q,\n", e.Schema+"."+e.Table, pk, e.DefaultSort)
	b.WriteString("\tFields: []query.Field{\n")
	for _, f := range e.Fields {
		if !f.Exposed {
			continue
		}
		fmt.Fprintf(b, "\t\t{Name: %q, Column: %q, Kind: %s, Ops: %s%s},\n",
			f.Name, f.Column, kindExpr(f.Kind), opsExpr(f), enumExpr(f))
	}
	b.WriteString("\t},\n}\n\n")

	fmt.Fprintf(b, "// singular names the resource in handler error messages (%q).\n", e.Name+" not found")
	fmt.Fprintf(b, "const singular = %q\n", e.Name)
	if hasWriteOp(e) {
		b.WriteString("\n// table is the short table name carried on the write commit.\n")
		fmt.Fprintf(b, "const table = %q\n", e.Table)
	}

	return formatGo(b.String())
}

// emitOp writes one endpoint file with the full handler inlined.
func emitOp(e schema.Entity, op schema.APIOp) (string, error) {
	switch op.Op {
	case "list":
		return emitList(e, op)
	case "get":
		return emitGet(e, op)
	case "create":
		return emitCreate(e, op)
	case "update":
		return emitUpdate(e, op)
	case "delete":
		return emitDelete(e, op)
	}
	return "", fmt.Errorf("entity %s: unknown api op %q", e.Table, op.Op)
}

// gateArg renders an op's required-actions argument to rest.Gate: nil when the
// op is open to any member, else an inline []string{...} of core action
// constants. The bool reports whether the core package is referenced.
func gateArg(requires []string) (string, bool, error) {
	if len(requires) == 0 {
		return "nil", false, nil
	}
	acts, err := actionExprs(requires)
	if err != nil {
		return "", false, err
	}
	return "[]string{" + acts + "}", true, nil
}

// gateBlock is the shared handler prologue: resolve the actor and enforce the
// op's required actions, 403 otherwise.
func gateBlock(b *strings.Builder, gate string) {
	b.WriteString("\t\ta := authz.ActorOf(r)\n")
	fmt.Fprintf(b, "\t\tif !rest.Gate(a, %s) {\n", gate)
	b.WriteString("\t\t\trest.WriteError(w, http.StatusForbidden, \"forbidden\")\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
}

func emitList(e schema.Entity, op schema.APIOp) (string, error) {
	plural := codegen.Plural(e.Name)
	gate, core, err := gateArg(op.Requires)
	if err != nil {
		return "", err
	}

	b := &strings.Builder{}
	b.WriteString(genHeader)
	fmt.Fprintf(b, "package %s\n\n", e.Table)
	b.WriteString(imports(
		group(q("net/http"), q("strconv")),
		group(q(pkgDB), q(pkgQuery), q(pkgRest), q(pkgAuthz)),
		coreGroup(core),
	))

	fmt.Fprintf(b, "// List handles GET /%s: a workspace-scoped, soft-delete-filtered list with\n", plural)
	b.WriteString("// OData $filter, sort, and keyset pagination, returning the\n")
	b.WriteString("// {data, next_cursor} envelope.\n")
	b.WriteString("func List() http.HandlerFunc {\n")
	b.WriteString("\treturn func(w http.ResponseWriter, r *http.Request) {\n")
	gateBlock(b, gate)
	b.WriteString("\t\tq := r.URL.Query()\n")
	b.WriteString("\t\tlimit, _ := strconv.Atoi(q.Get(\"limit\"))\n")
	b.WriteString("\t\tpage, err := query.List(r.Context(), db.GetDB(), resource, query.Request{\n")
	b.WriteString("\t\t\tWorkspaceID: a.WorkspaceID,\n")
	b.WriteString("\t\t\tFilter:      q.Get(\"$filter\"),\n")
	b.WriteString("\t\t\tSort:        q.Get(\"sort\"),\n")
	b.WriteString("\t\t\tLimit:       limit,\n")
	b.WriteString("\t\t\tCursor:      q.Get(\"cursor\"),\n")
	b.WriteString("\t\t})\n")
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\trest.WriteQueryError(w, err)\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\trest.WriteJSON(w, http.StatusOK, page)\n")
	b.WriteString("\t}\n}\n")
	return formatGo(b.String())
}

