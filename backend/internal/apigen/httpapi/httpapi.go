func emitCreate(e schema.Entity, op schema.APIOp) (string, error) {
	plural := codegen.Plural(e.Name)
	gate, core, err := gateArg(op.Requires)
	if err != nil {
		return "", err
	}

	b := &strings.Builder{}
	b.WriteString(genHeader)
	fmt.Fprintf(b, "package %s\n\n", e.Table)
	b.WriteString(imports(
		group(q("net/http"), q("time")),
		group(q(pkgDB), q(pkgQuery), q(pkgRest), q(pkgAuthz), q(pkgTypes)),
		coreGroup(core),
		group(fmt.Sprintf("syncgen %q", "backend/internal/syncer/gen/"+e.Table)),
	))

	fmt.Fprintf(b, "// Create handles POST /%s: create a row from the request body. The client\n", plural)
	b.WriteString("// supplies the id. The write goes through the syncer's Apply, so tenancy, the\n")
	b.WriteString("// cross-workspace FK guard, LWW, and audit emission match the sync path.\n")
	b.WriteString("func Create() http.HandlerFunc {\n")
	b.WriteString("\treturn func(w http.ResponseWriter, r *http.Request) {\n")
	gateBlock(b, gate)
	b.WriteString("\t\tbody, ok := rest.DecodeBody(w, r)\n")
	b.WriteString("\t\tif !ok {\n\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\tid, _ := body[\"id\"].(string)\n")
	b.WriteString("\t\tif id == \"\" {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusBadRequest, \"id is required\")\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\tif _, found, err := query.Get(r.Context(), db.GetDB(), resource, a.WorkspaceID, id); err != nil {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusInternalServerError, \"internal error\")\n")
	b.WriteString("\t\t\treturn\n")
	b.WriteString("\t\t} else if found {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusConflict, singular+\" already exists\")\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
	writeCommit(b, "create", `body`)
	b.WriteString("\t\tapplied, _, err := syncgen.Apply(r.Context(), a.UserID, c, time.Time{})\n")
	writeApplyErr(b)
	b.WriteString("\t\tif !applied { // LWW rejected it (e.g. a soft-deleted row holds this id)\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusConflict, singular+\" already exists\")\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
	writeReadBack(b, "http.StatusCreated")
	b.WriteString("\t}\n}\n")
	return formatGo(b.String())
}

