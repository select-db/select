// writeCommit emits the synthesized syncer commit the write delegates to,
// stamped with server time (the server is authoritative, so LWW resolves in the
// request's favor barring a truly concurrent write).
func writeCommit(b *strings.Builder, op, payload string) {
	b.WriteString("\t\tc := types.Commit{\n")
	fmt.Fprintf(b, "\t\t\tID:          id + %q,\n", ":"+op)
	b.WriteString("\t\t\tCreatedAt:   time.Now(),\n")
	fmt.Fprintf(b, "\t\t\tOperation:   %q,\n", op)
	b.WriteString("\t\t\tTableName:   table,\n")
	b.WriteString("\t\t\tObjectID:    id,\n")
	fmt.Fprintf(b, "\t\t\tPayload:     %s,\n", payload)
	b.WriteString("\t\t\tUserID:      a.UserID,\n")
	b.WriteString("\t\t\tWorkspaceID: a.WorkspaceID,\n")
	b.WriteString("\t\t}\n")
}

// writeApplyErr emits the shared Apply error mapping: a predominantly
// client-caused failure (cross-workspace FK, invalid uuid, stale row) becomes a
// generic 422 rather than risk leaking an internal DB message.
func writeApplyErr(b *strings.Builder) {
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusUnprocessableEntity, \"could not process the \"+singular)\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
}

// writeReadBack emits the post-write re-read so the client sees the
// server-canonical row (server-set updated_at, applied defaults). A row applied
// but no longer readable (raced with a delete) reports success without a body.
func writeReadBack(b *strings.Builder, status string) {
	b.WriteString("\t\trow, found, err := query.Get(r.Context(), db.GetDB(), resource, a.WorkspaceID, id)\n")
	b.WriteString("\t\tif err != nil {\n")
	b.WriteString("\t\t\trest.WriteError(w, http.StatusInternalServerError, \"internal error\")\n")
	b.WriteString("\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\tif !found {\n")
	fmt.Fprintf(b, "\t\t\tw.WriteHeader(%s)\n", status)
	b.WriteString("\t\t\treturn\n\t\t}\n")
	fmt.Fprintf(b, "\t\trest.WriteJSON(w, %s, row)\n", status)
}

// emitEntityRoutes writes the entity's Register: it mounts each declared op on
// its REST path with the shared middleware chain at the per-op rate.
func emitEntityRoutes(e schema.Entity) (string, error) {
	plural := codegen.Plural(e.Name)
	b := &strings.Builder{}
	b.WriteString(genHeader)
	fmt.Fprintf(b, "package %s\n\n", e.Table)
	b.WriteString("import (\n\t\"net/http\"\n\n\t\"backend/internal/api/rest\"\n)\n\n")
	fmt.Fprintf(b, "// Register mounts the %s endpoints on mux.\n", e.Name)
	b.WriteString("func Register(mux *http.ServeMux, wrap rest.Wrap) {\n")
	for _, op := range e.API {
		fmt.Fprintf(b, "\tmux.Handle(%q, wrap(rest.%s, %s()))\n",
			method(op.Op)+" "+path(op.Op, plural), rateConst(op.Op), opFn(op.Op))
	}
	b.WriteString("}\n")
	return formatGo(b.String())
}

// emitTopRoutes writes internal/api/gen/routes.go, which calls each entity
// package's Register.
func emitTopRoutes(apis []schema.Entity) (codegen.GenFile, error) {
	b := &strings.Builder{}
	b.WriteString(genHeader)
	b.WriteString("package gen\n\n")
	b.WriteString("import (\n\t\"net/http\"\n\n\t\"backend/internal/api/rest\"\n\n")
	for _, e := range apis {
		fmt.Fprintf(b, "\t%s %q\n", e.Table, "backend/internal/api/gen/"+e.Table)
	}
	b.WriteString(")\n\n")
	b.WriteString("// RegisterRoutes wires every generated REST resource onto mux with the shared\n")
	b.WriteString("// middleware chain (authenticated, WorkspaceFromHeader, limited) the api\n")
	b.WriteString("// package supplies.\n")
	b.WriteString("func RegisterRoutes(mux *http.ServeMux, wrap rest.Wrap) {\n")
	for _, e := range apis {
		fmt.Fprintf(b, "\t%s.Register(mux, wrap)\n", e.Table)
	}
	b.WriteString("}\n")
	c, err := formatGo(b.String())
	if err != nil {
		return codegen.GenFile{}, err
	}
	return codegen.GenFile{Name: "routes.go", Content: c}, nil
}

// imports renders one import block from ordered groups, each group separated by
// a blank line (stdlib, backend, core, syncgen). Empty groups are dropped.
// format.Source sorts within each group.
func imports(groups ...[]string) string {
	b := &strings.Builder{}
	b.WriteString("import (\n")
	first := true
	for _, g := range groups {
		if len(g) == 0 {
			continue
		}
		if !first {
			b.WriteString("\n")
		}
		first = false
		for _, imp := range g {
			b.WriteString("\t" + imp + "\n")
		}
	}
	b.WriteString(")\n\n")
	return b.String()
}

func group(imps ...string) []string { return imps }

// q quotes a bare import path.
func q(path string) string { return fmt.Sprintf("%q", path) }

// coreGroup is the dialect/core import group, present only when the file gates
// on a core action constant.
func coreGroup(use bool) []string {
	if !use {
		return nil
	}
	return []string{pkgCore}
}

func formatGo(src string) (string, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return "", fmt.Errorf("format: %w\n---\n%s", err, src)
	}
	return string(out), nil
}

// opFn is the exported handler/registration name for an op (list -> List).
func opFn(op string) string { return strings.ToUpper(op[:1]) + op[1:] }

func method(op string) string {
	switch op {
	case "create":
		return "POST"
	case "update":
		return "PATCH"
	case "delete":
		return "DELETE"
	default: // list, get
		return "GET"
	}
}

func path(op, plural string) string {
	switch op {
	case "list", "create":
		return "/" + plural
	default: // get, update, delete
		return "/" + plural + "/{id}"
	}
}

func rateConst(op string) string {
	switch op {
	case "create", "update", "delete":
		return "WriteRate"
	default:
		return "ReadRate"
	}
}

func hasWriteOp(e schema.Entity) bool {
	for _, op := range e.API {
		switch op.Op {
		case "create", "update", "delete":
			return true
		}
	}
	return false
}

func pkFieldName(e schema.Entity) (string, error) {
	if len(e.PrimaryKey) == 0 {
		return "", fmt.Errorf("entity %s has no primary key", e.Table)
	}
	for _, f := range e.Fields {
		if f.Column == e.PrimaryKey[0] {
			return f.Name, nil
		}
	}
	return "", fmt.Errorf("entity %s: no field for primary-key column %q", e.Table, e.PrimaryKey[0])
}

func kindExpr(k schema.Kind) string {
	switch k {
	case schema.KindUUID:
		return "query.KindUUID"
	case schema.KindInt:
		return "query.KindInt"
	case schema.KindTime:
		return "query.KindTime"
	case schema.KindBool:
		return "query.KindBool"
	case schema.KindJSON:
		return "query.KindJSON"
	case schema.KindInet:
		return "query.KindInet"
	default: // text
		return "query.KindText"
	}
}

func opsExpr(f schema.Field) string {
	toks := schema.ODataOperators(f)
	parts := make([]string, 0, len(toks))
	for _, t := range toks {
		parts = append(parts, opConst(t))
	}
	return "[]query.Op{" + strings.Join(parts, ", ") + "}"
}

func opConst(tok string) string {
	switch tok {
	case "eq":
		return "query.OpEq"
	case "ne":
		return "query.OpNe"
	case "lt":
		return "query.OpLt"
	case "le":
		return "query.OpLe"
	case "gt":
		return "query.OpGt"
	case "ge":
		return "query.OpGe"
	case "in":
		return "query.OpIn"
	case "not in":
		return "query.OpNotIn"
	case "contains":
		return "query.OpContains"
	case "startswith":
		return "query.OpStartsWith"
	case "endswith":
		return "query.OpEndsWith"
	}
	return ""
}

func enumExpr(f schema.Field) string {
	if len(f.Values) == 0 {
		return ""
	}
	qs := make([]string, len(f.Values))
	for i, v := range f.Values {
		qs[i] = fmt.Sprintf("%q", v)
	}
	return ", Enum: []string{" + strings.Join(qs, ", ") + "}"
}

func actionExprs(requires []string) (string, error) {
	parts := make([]string, len(requires))
	for i, r := range requires {
		c, ok := syncer.ActionConst(r)
		if !ok {
			return "", fmt.Errorf("unknown requires action %q", r)
		}
		parts[i] = c
	}
	return strings.Join(parts, ", "), nil
}
